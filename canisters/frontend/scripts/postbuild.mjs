// Runs after `react-router build`:
// 1. Renames prerendered <page>/index.html to <page>.html so the canister's clean
//    URLs match the spec (/integritet, /en/privacy, /404.html).
// 2. Writes sitemap.xml and robots.txt.
// 3. Appends a per-file Content-Security-Policy to _headers, allowing each file's
//    inline scripts (React Router hydration) by sha256 hash, never 'unsafe-inline'.
import { createHash } from "node:crypto";
import { appendFileSync, readdirSync, readFileSync, renameSync, rmSync, rmdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE_URL = "https://axelkod.eu";
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../build/client");

for (const page of ["integritet", "en/privacy", "404"]) {
  renameSync(join(out, page, "index.html"), join(out, `${page}.html`));
  rmdirSync(join(out, page));
}
// SPA mode's fallback shell is unused: unknown paths get 404.html. (Admin shell: Phase 5a.)
rmSync(join(out, "__spa-fallback.html"), { force: true });

const pages = [
  { sv: "/", en: "/en/" },
  { sv: "/integritet", en: "/en/privacy" },
];
const urls = pages.flatMap((p) =>
  ["sv", "en"].map(
    (lang) => `  <url>
    <loc>${SITE_URL}${p[lang]}</loc>
    <xhtml:link rel="alternate" hreflang="sv" href="${SITE_URL}${p.sv}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${SITE_URL}${p.en}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE_URL}${p.sv}"/>
  </url>`,
  ),
);
writeFileSync(
  join(out, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join("\n")}
</urlset>
`,
);
writeFileSync(
  join(out, "robots.txt"),
  `User-agent: *
Allow: /
Disallow: /admin

Sitemap: ${SITE_URL}/sitemap.xml
`,
);

const htmlFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return e.name === "assets" ? [] : htmlFiles(p);
    return e.name.endsWith(".html") ? [p] : [];
  });

const inlineScript = /<script\b(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g;
let blocks = "\n# --- generated by scripts/postbuild.mjs ---\n";
for (const file of htmlFiles(out).sort()) {
  const html = readFileSync(file, "utf8");
  const hashes = new Set();
  for (const [, attrs, body] of html.matchAll(inlineScript)) {
    if (/type=["']application\/ld\+json["']/.test(attrs)) continue; // data, not code
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${[...hashes].join(" ")}`.trim(),
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    // The agent calls the page origin locally and icp-api.io on custom domains.
    "connect-src 'self' https://icp-api.io",
    "manifest-src 'self'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "object-src 'none'",
  ].join("; ");
  blocks += `\n/${relative(out, file)}\n  Content-Security-Policy: ${csp}\n`;
}
appendFileSync(join(out, "_headers"), blocks);
console.log(`postbuild: ${htmlFiles(out).length} HTML files, CSP written to _headers`);
